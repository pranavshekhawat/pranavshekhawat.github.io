/**
 * Get all Hindi translations for an ingredient
 * @param {string} key - Ingredient key (e.g., "coconut_oil", "turmeric")
 * @returns {{ hindi: string, romanized: string } | null}
 */
export const getHindiName = (key) => {
  if (!key) return null;
  const normalizedKey = key.toLowerCase().replace(/[\s-]/g, "_");
  
  return (
    OIL_NAMES_HINDI[normalizedKey] ||
    BUTTER_NAMES_HINDI[normalizedKey] ||
    ESSENTIAL_OIL_NAMES_HINDI[normalizedKey] ||
    ADDITIVE_NAMES_HINDI[normalizedKey] ||
    AYURVEDIC_NAMES_HINDI[normalizedKey] ||
    SOAP_TERMS_HINDI[normalizedKey] ||
    null
  );
};

