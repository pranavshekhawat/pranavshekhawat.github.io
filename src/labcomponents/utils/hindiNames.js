export const suggestHindiRecipeName = (mainIngredients = []) => {
  if (!mainIngredients.length) return RECIPE_NAME_SUGGESTIONS.sundari;
  
  const primary = mainIngredients[0]?.toLowerCase().replace(/[\s-]/g, "_");
  
  // Check direct recipe matches
  if (RECIPE_NAME_SUGGESTIONS[`${primary}_soap`]) {
    return RECIPE_NAME_SUGGESTIONS[`${primary}_soap`];
  }
  
  // Check ingredient name and create compound
  const hindiIngredient = getHindiName(primary);
  if (hindiIngredient) {
    return {
      hindi: `${hindiIngredient.hindi} साबुन`,
      romanized: `${hindiIngredient.romanized} Sabun`,
    };
  }
  
  // Fallback to a poetic name
  const poeticNames = ['sundari', 'nirmal', 'sneha', 'kanti', 'lavanya'];
  const randomPoetic = poeticNames[Math.floor(Math.random() * poeticNames.length)];
  return RECIPE_NAME_SUGGESTIONS[randomPoetic];
};

/**
 * Format ingredient with Hindi name for display
 * @param {string} name - English name
 * @param {string} key - Ingredient key
 * @param {boolean} showHindiScript - Whether to show Devanagari script
 * @returns {string} - Formatted name
 */
export const formatIngredientWithHindi = (name, key, showHindiScript = true) => {
  const hindi = getHindiName(key);
  if (!hindi) return name;
  
  if (showHindiScript) {
    return `${name} (${hindi.hindi} - ${hindi.romanized})`;
  }
  return `${name} (${hindi.romanized})`;
};

/**
 * Get all ingredients with Hindi names as array for dropdown/display
 * @returns {Array} - Array of { key, english, hindi, romanized }
 */
export const getAllIngredientsWithHindi = () => {
  const allMaps = [
    { map: OIL_NAMES_HINDI, category: 'oil' },
    { map: BUTTER_NAMES_HINDI, category: 'butter' },
    { map: ESSENTIAL_OIL_NAMES_HINDI, category: 'essential_oil' },
    { map: ADDITIVE_NAMES_HINDI, category: 'additive' },
    { map: AYURVEDIC_NAMES_HINDI, category: 'ayurvedic' },
  ];
  
  const seen = new Set();
  const results = [];
  
  allMaps.forEach(({ map, category }) => {
    Object.entries(map).forEach(([key, value]) => {
      // Skip duplicates (same hindi name)
      const uniqueKey = `${value.hindi}`;
      if (seen.has(uniqueKey)) return;
      seen.add(uniqueKey);
      
      results.push({
        key,
        english: key.replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase()),
        hindi: value.hindi,
        romanized: value.romanized,
        category,
      });
    });
  });
  
  return results;
};

